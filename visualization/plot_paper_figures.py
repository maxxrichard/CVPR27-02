"""Result figures for the manuscript.  Reads results/raw/ when real runs exist, otherwise results/placeholder/
(generated by scripts/make_placeholder_results.py) and stamps the figure with a PLACEHOLDER watermark.
Also draws a 2-D embedding view of the mechanism on the synthetic generator used by the unit tests (labelled as
synthetic) and a qualitative-prediction grid (placeholder slots until real images/predictions are supplied).
Usage: python visualization/plot_paper_figures.py
"""
import glob, json, os, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
RAW, PH = os.path.join(ROOT, "results", "raw"), os.path.join(ROOT, "results", "placeholder")
OUT = [os.path.join(ROOT, "paper", "figures"), os.path.join(ROOT, "figures", "quantitative")]
plt.rcParams.update({"font.size": 7, "pdf.fonttype": 42, "font.family": "DejaVu Sans"})
STYLE = {"zero_shot": ("CLIP zero-shot", "#6b7280"), "transclip": ("TransCLIP", "#94a3b8"), "stata": ("StatA", "#2563eb"),
         "moon": ("MOON", "#7c3aed"), "count_shrinkage": ("anchor-only control", "#60a5fa"), "graft": ("GRAFT", "#c2610a")}
SETTINGS = [("64", "1-4", "very low"), ("64", "2-10", "low"), ("64", "5-25", "medium"), ("1000", "5-25", "medium"), ("1000", "25-50", "high"), ("1000", "50-100", "very high"), ("-1", "all", "all")]


def src():
    return (RAW, False) if glob.glob(os.path.join(RAW, "avg11_*.json")) else (PH, True)


def watermark(fig, ph):
    if ph:
        fig.text(0.5, 0.5, "PLACEHOLDER DATA", ha="center", va="center", fontsize=22, color="red", alpha=0.18, rotation=25, weight="bold")


def save(fig, name):
    for o in OUT:
        os.makedirs(o, exist_ok=True); fig.savefig(os.path.join(o, name), bbox_inches="tight")
    plt.close(fig); print("wrote", name)


def load(d, pat):
    return {os.path.basename(f): json.load(open(f)) for f in glob.glob(os.path.join(d, pat))}


def bar_keff():
    d, ph = src()
    fig, ax = plt.subplots(figsize=(3.4, 1.9))
    meths = ["zero_shot", "transclip", "stata", "moon", "count_shrinkage", "graft"]
    w = 0.13; xs = np.arange(len(SETTINGS))
    for i, m in enumerate(meths):
        ys, es = [], []
        for B, K, _ in SETTINGS:
            r = load(d, f"avg11_B{B}_K{K}_{m}.json")
            v = next(iter(r.values()), None)
            ys.append(v["acc_mean"] if v else np.nan); es.append((v or {}).get("acc_std") or 0)
        lab, col = STYLE[m]
        ax.bar(xs + (i - len(meths) / 2 + 0.5) * w, ys, w, yerr=es, color=col, label=lab, error_kw=dict(lw=0.5, capsize=1))
    ax.set_xticks(xs); ax.set_xticklabels([f"{n}\nB={B if B != '-1' else 'all'}" for B, K, n in SETTINGS], fontsize=5.5)
    ax.set_ylim(25, 75); ax.set_ylabel("top-1 accuracy (%)"); ax.set_xlabel("effective classes per batch")
    ax.legend(fontsize=5, ncol=3, frameon=False, loc="lower right"); ax.grid(axis="y", alpha=0.3)
    watermark(fig, ph); save(fig, "plot_keff_bar.pdf")


def sensitivity():
    d, ph = src()
    files = load(d, "sens_*.json")
    if not files:
        return
    data = {}
    for r in files.values():
        data.setdefault(r["param"], {})[float(r["value"])] = (r["acc_mean"], r.get("acc_std", 0))
    names = {"alpha": r"anchor strength $\alpha$", "lam": r"graph coupling $\lambda$", "knn": "neighbours $m$"}
    fig, axes = plt.subplots(1, len(data), figsize=(3.4, 1.3))
    for ax, p in zip(axes, ["alpha", "lam", "knn"]):
        v = sorted(data[p]); ax.errorbar(range(len(v)), [data[p][x][0] for x in v], yerr=[data[p][x][1] for x in v], marker="o", ms=3, color="#c2610a", lw=1, capsize=1.5)
        ax.set_xticks(range(len(v))); ax.set_xticklabels([f"{x:g}" for x in v], fontsize=5.5); ax.set_xlabel(names[p], fontsize=6); ax.grid(alpha=0.3)
    axes[0].set_ylabel("accuracy (%)", fontsize=6)
    plt.subplots_adjust(wspace=0.35)
    watermark(fig, ph); save(fig, "plot_sensitivity.pdf")


def smoothness():
    d, ph = src()
    files = load(d, "smooth_*.json")
    if not files:
        return
    rs = sorted(files.values(), key=lambda r: r["features"])
    fig, ax = plt.subplots(figsize=(3.4, 1.35))
    names = [r["features"].split("__")[0].replace("_", " ") for r in rs]
    ax.bar(np.arange(len(rs)), [r["ratio"] for r in rs], yerr=[r.get("random_std", 0) for r in rs], color="#c2610a", error_kw=dict(lw=0.5, capsize=1))
    ax.axhline(1.0, color="#6b7280", ls="--", lw=0.8); ax.set_xticks(np.arange(len(rs))); ax.set_xticklabels(names, rotation=40, ha="right", fontsize=5.5)
    ax.set_ylabel("energy ratio\n(text graph / random)", fontsize=6); ax.set_ylim(0, 1.15)
    watermark(fig, ph); save(fig, "plot_smoothness.pdf")


def embedding_view():
    """2-D PCA of a synthetic hyperspherical mixture (tests/synthetic.py) with 6 of 24 classes present."""
    import torch
    from tests.synthetic import make_problem
    from graft import GRAFTConfig, graft_batch
    present = [0, 1, 6, 7, 12, 13]
    X, Y, T, Dtrue = make_problem(K=24, d=48, n_per_class=25, present=present, seed=11)
    cfg = GRAFTConfig(sample_knn=0)
    _, _, st_g = graft_batch(X, T, cfg, return_state=True)
    import dataclasses
    _, _, st_a = graft_batch(X, T, dataclasses.replace(cfg, lam=0.0), return_state=True)
    Mu_true = torch.nn.functional.normalize(T + Dtrue, dim=-1)
    allpts = torch.cat([X, T, Mu_true]); mean = allpts.mean(0)
    U, S, V = torch.pca_lowrank(allpts - mean, q=2)
    P = lambda Z: ((Z - mean) @ V[:, :2]).numpy()
    fig, axes = plt.subplots(1, 2, figsize=(3.4, 1.7), sharex=True, sharey=True)
    absent = [k for k in range(24) if k not in present]
    for ax, st, title in zip(axes, [st_a, st_g], ["(a) anchor-only ($\\lambda=0$)", "(b) GRAFT ($\\lambda>0$)"]):
        x = P(X); ax.scatter(x[:, 0], x[:, 1], s=2, c=Y.numpy(), cmap="tab20", alpha=0.5, lw=0)
        t = P(T); m = P(torch.nn.functional.normalize(st.Mu, dim=-1)); mt = P(Mu_true)
        ax.scatter(t[:, 0], t[:, 1], marker="*", s=18, c="#374151", label="text anchor", zorder=4)
        ax.scatter(mt[absent, 0], mt[absent, 1], marker="o", s=14, facecolors="none", edgecolors="#c2610a", lw=0.7, label="true centroid (absent)", zorder=4)
        for k in range(24):
            ax.annotate("", xy=m[k], xytext=t[k], arrowprops=dict(arrowstyle="-|>", lw=0.6, color="#c2610a" if k in absent else "#2563eb", mutation_scale=5))
        ax.set_title(title, fontsize=6.5); ax.set_xticks([]); ax.set_yticks([])
    axes[0].legend(fontsize=4.5, frameon=False, loc="lower left")
    fig.text(0.5, -0.02, "Synthetic illustration (unit-test generator, PCA to 2-D); arrows: anchor to adapted prototype, orange = absent classes.", ha="center", fontsize=4.8, style="italic")
    plt.subplots_adjust(wspace=0.05)
    save(fig, "plot_embedding_synthetic.pdf")


def qualitative_grid(n_rows=2, n_cols=4):
    """Grid of test images with predictions of zero-shot / StatA / GRAFT.  Real inputs: a JSON list of
    {image, label, zs, stata, graft} under results/raw/qualitative.json; otherwise placeholder slots."""
    f = os.path.join(RAW, "qualitative.json")
    items = json.load(open(f)) if os.path.exists(f) else None
    fig, axes = plt.subplots(n_rows, n_cols, figsize=(3.4, 2.3))
    for i, ax in enumerate(axes.ravel()):
        ax.set_xticks([]); ax.set_yticks([])
        if items and i < len(items):
            it = items[i]; ax.imshow(plt.imread(it["image"]))
            ax.set_xlabel(f"GT: {it['label']}\nZS: {it['zs']}\nStatA: {it['stata']}\nGRAFT: {it['graft']}", fontsize=4.3)
        else:
            ax.set_facecolor("#e5e7eb"); ax.text(0.5, 0.55, "image\nplaceholder", ha="center", va="center", fontsize=5, color="#6b7280", transform=ax.transAxes)
            ax.set_xlabel("GT: class name\nZS: wrong\nStatA: wrong\nGRAFT: correct", fontsize=4.3, color="#9ca3af")
    plt.subplots_adjust(wspace=0.12, hspace=1.1)
    watermark(fig, items is None); save(fig, "plot_qualitative.pdf")


if __name__ == "__main__":
    bar_keff(); sensitivity(); smoothness(); embedding_view(); qualitative_grid()
