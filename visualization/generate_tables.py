"""Generate the LaTeX result tables from results/raw/*.json.  Missing entries are rendered as `TBD'.
Writes paper/tables/*.tex (included by the manuscript).  Usage: python visualization/generate_tables.py
"""
import glob, json, os, re
import numpy as np

RAW = os.path.join(os.path.dirname(__file__), "..", "results", "raw")
OUT = os.path.join(os.path.dirname(__file__), "..", "paper", "tables")
os.makedirs(OUT, exist_ok=True)
DATASETS = ["imagenet", "sun397", "fgvc", "eurosat", "stanford_cars", "food101", "oxford_pets", "oxford_flowers", "caltech101", "dtd", "ucf101"]
SETTINGS = [("64", "1-4", "Very low"), ("64", "2-10", "Low"), ("64", "5-25", "Medium"), ("1000", "5-25", "Medium"), ("1000", "25-50", "High"), ("1000", "50-100", "Very high"), ("-1", "all", "All")]
METHODS = [("zero_shot", "CLIP zero-shot"), ("count_shrinkage", "Anchor-only shrinkage"), ("global_shift", "Complete pooling"), ("label_shift_only", "Presence only"), ("graft", "GRAFT"), ("graft_eb", "GRAFT + EB")]


def cell(meth, B, K):
    vals = []
    for ds in DATASETS:
        f = os.path.join(RAW, f"{ds}_B{B}_K{K}_{meth}.json")
        if os.path.exists(f):
            vals.append(json.load(open(f))["acc_mean"])
    if len(vals) == len(DATASETS):
        return f"{np.mean(vals):.1f}"
    if vals:
        return f"{np.mean(vals):.1f}$^{{({len(vals)}/{len(DATASETS)})}}$"
    return "TBD"


def table_main():
    lines = ["% auto-generated by visualization/generate_tables.py", "\\begin{tabular}{l" + "c" * len(SETTINGS) + "}", "\\toprule",
             "Method & " + " & ".join(f"{n}" for _, _, n in SETTINGS) + " \\\\", " & " + " & ".join(f"$B{{=}}{B}$" if B != "-1" else "full" for B, _, _ in SETTINGS) + " \\\\", "\\midrule"]
    for m, name in METHODS:
        lines.append(name + " & " + " & ".join(cell(m, B, K) for B, K, _ in SETTINGS) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(OUT, "table_main_generated.tex"), "w").write("\n".join(lines) + "\n")


def table_online():
    gammas = [("0.1", "Low corr."), ("0.01", "Medium"), ("0.001", "High"), ("-1.0", "Separate")]
    lines = ["% auto-generated", "\\begin{tabular}{lcccc}", "\\toprule", "Method & " + " & ".join(n for _, n in gammas) + " \\\\", "\\midrule"]
    for m, name in [("zero_shot", "CLIP zero-shot"), ("graft", "GRAFT"), ("graft_eb", "GRAFT + EB")]:
        cells = []
        for g, _ in gammas:
            vals = [json.load(open(f))["acc_mean"] for ds in DATASETS for f in [os.path.join(RAW, f"{ds}_online_g{g}_{m}.json")] if os.path.exists(f)]
            cells.append(f"{np.mean(vals):.1f}" if len(vals) == len(DATASETS) else (f"{np.mean(vals):.1f}$^{{({len(vals)}/{len(DATASETS)})}}$" if vals else "TBD"))
        lines.append(name + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(os.path.join(OUT, "table_online_generated.tex"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    table_main(); table_online(); print("tables written to", OUT)
